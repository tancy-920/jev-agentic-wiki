"""Exact historical ranking/navigation functions, stdlib article loader.
Generated by scripts/build_public_experiments.py; ranking checked against all original rows.
"""
import json
import math
import hashlib
import re
from collections import Counter, deque
from pathlib import Path
from types import SimpleNamespace


def tokens(text):
    words = set(re.findall(r"[a-z0-9_]+", text.lower()))
    for phrase in re.findall(r"[\u4e00-\u9fff]+", text):
        words.update(phrase[i:i + 2] for i in range(len(phrase) - 1))
    return words

def article_content(text):
    """Provenance and link lists are metadata, never topical matching evidence."""
    return re.split(r"^## (?:来源追溯|关联知识)\s*$", text, maxsplit=1, flags=re.M)[0]

def alias_match(alias, query):
    # Apply identifier boundaries to phrases/hyphenated aliases as well as words.
    left = r"(?<![a-z0-9_])" if re.match(r"[a-zA-Z0-9_]", alias) else ""
    right = r"(?![a-z0-9_])" if re.search(r"[a-zA-Z0-9_]$", alias) else ""
    return bool(alias) and re.search(left + re.escape(alias.lower()) + right, query.lower()) is not None


class ArticleStore:
    def __init__(self, root):
        root = Path(root).resolve()
        manifest = json.loads((root / "manifest.json").read_text(encoding="utf8"))
        self.pages = {r["article_id"]: SimpleNamespace(**r) for r in manifest["articles"]}
        self.content_tokens, self.title_tokens = {}, {}
        for identifier, row in self.pages.items():
            path = (root / row.markdown_file).resolve()
            if not path.is_relative_to(root) or hashlib.sha256(path.read_bytes()).hexdigest() != row.sha256:
                raise ValueError("Wiki path/hash mismatch")
            text = path.read_text(encoding="utf8")
            if not set(row.related) <= set(self.pages):
                raise ValueError("Dangling edge")
            self.content_tokens[identifier] = tokens(article_content(text))
            self.title_tokens[identifier] = tokens(" ".join([row.title, *row.aliases]))
        frequencies = Counter(t for ts in self.content_tokens.values() for t in ts)
        self.idf = {t: math.log(1 + len(self.pages)/(1 + count)) for t, count in frequencies.items()}

    def topical_score(self, identifier, query_tokens):
        title = query_tokens & self.title_tokens[identifier]
        body = query_tokens & self.content_tokens[identifier]
        return sum(3*self.idf.get(t, 1) for t in title) + sum(self.idf.get(t, 1) for t in body)


def rank_direct(store, query):
    terms = tokens(query)
    ranked = []
    for identifier, row in store.pages.items():
        title = terms & store.title_tokens[identifier]
        body = terms & store.content_tokens[identifier]
        exact = any(alias_match(a, query) for a in [row.title, *row.aliases])
        if exact or title or len(body) >= 2:
            score = store.topical_score(identifier, terms) + 3 * exact
            ranked.append((score, identifier))
    return [identifier for _, identifier in sorted(ranked, key=lambda r: (-r[0], r[1]))]

def shortest_paths(edges, start):
    paths = {start: [start]}
    queue = deque([start])
    while queue:
        node = queue.popleft()
        for neighbor in sorted(edges[node]):
            if neighbor not in paths:
                paths[neighbor] = [*paths[node], neighbor]
                queue.append(neighbor)
    return paths

def recommend(store, edges, start, query):
    # Same global search, even for graph-unreachable articles. Targets unseen.
    ranking = [i for i in rank_direct(store, query) if i != start]
    # Catalog fallback is shared and recorded, not graph-only information.
    ranking += sorted(set(store.pages) - {start} - set(ranking))
    direct = ranking[:6]
    paths = shortest_paths(edges, start)
    selected = direct[:3]
    neighbors = sorted((i for i, p in paths.items()
                        if i != start and len(p) <= 4 and i not in selected),
                       key=lambda i: (len(paths[i]), ranking.index(i), i))
    for candidate in [*neighbors, *ranking]:
        if candidate not in selected and len(selected) < 6:
            selected.append(candidate)
    return direct, selected, paths

def aggregate(rows, arm):
    hits = [len(set(row[arm]) & set(row["targets"])) for row in rows]
    return dict(hits=sum(hits), targets=sum(len(r["targets"]) for r in rows),
                micro_recall=sum(hits) / sum(len(r["targets"]) for r in rows),
                macro_recall=sum(h / len(r["targets"]) for h, r in zip(hits, rows, strict=True)) / len(rows),
                target_density=sum(hits) / sum(len(r[arm]) for r in rows))
